def admin():
    d = Diagram('Activity Diagram — System Admin', [('System Admin', *ADM, 640), (SYSTEM, *SYS, 460)])
    d.n('start', 'start', 0, 0, dx=MAIN)
    d.n('login', 'action', 0, 1, 'Log in through the\nadmin console', dx=MAIN)
    d.n('isAdmin', 'decision', 1, 2, 'Correct password &\nadmin account?')
    d.n('refused', 'action', 0, 2, 'Access refused', dx=SIDE)
    d.n('end1', 'end', 0, 3, dx=SIDE)
    d.n('dash', 'action', 1, 3.2, 'Show statistics, trends\n& pending applications')
    d.n('review', 'action', 0, 4.3, 'Review a doctor / lab\napplication (vs registry)', dx=MAIN)
    d.n('approve', 'decision', 0, 5.5, 'Approve?', dx=MAIN)
    d.n('reason', 'action', 0, 6.9, 'Write the\nrejection reason', dx=SIDE)
    d.n('activate', 'action', 1, 5.5, 'Activate the account\n(can now log in)')
    d.n('reject', 'action', 1, 6.9, 'Reject the application\n& sign it out')
    d.n('manage', 'action', 0, 8.1, 'Suspend / reactivate\nusers if needed', dx=MAIN)
    d.n('signout', 'action', 1, 9.1, 'A suspended user is\nsigned out at once')
    d.n('audit', 'action', 0, 10.1, 'Monitor the platform\naudit log', dx=MAIN)
    d.n('logout', 'action', 0, 11.1, 'Log out', dx=MAIN)
    d.n('end', 'end', 0, 12.1, dx=MAIN)

    d.e('start', 'login')
    d.e('login', 'isAdmin', mode='hv')
    d.e('isAdmin', 'refused', 'No', mode='h')
    d.e('refused', 'end1')
    d.e('isAdmin', 'dash', 'Yes')
    d.e('dash', 'review', mode='hv')
    d.e('review', 'approve')
    d.e('approve', 'activate', 'Yes', mode='h')
    d.e('approve', 'reason', 'No', mode='side-down', side='left')
    d.e('reason', 'reject', mode='h')
    d.e('activate', 'manage', mode='loop', side='right', off=0)
    rx, mx, y = d.cx(d.nodes['reject']), d.cx(d.nodes['manage']), d.cy(d.nodes['reject']) + 62
    d.e('reject', 'manage', mode='via', side='bottom>top', via=[(rx, y), (mx, y)])
    d.e('manage', 'signout', mode='down-across')
    d.e('signout', 'audit', mode='down-across')
    d.e('audit', 'logout')
    d.e('logout', 'end')
    return d


OUT.mkdir(parents=True, exist_ok=True)
for name, build in [('patient', patient), ('doctor', doctor), ('lab', lab), ('admin', admin)]:
    dg = build()
    (OUT / f'activity-{name}.svg').write_text(dg.svg(), encoding='utf-8')
    (OUT / f'HealthNexus-Activity-{name.capitalize()}.drawio').write_text(dg.drawio(f'activity-{name}'), encoding='utf-8')
    hits = dg.collisions()
    print(f'{name}: {len(dg.nodes)} nodes, {len(dg.edges)} edges, {len(hits)} crossings', *[f'\n   {h}' for h in hits])
