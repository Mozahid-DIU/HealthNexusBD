"""The four HealthNexus BD activity diagrams (Patient, Doctor, Lab, Admin)."""
import sys
from pathlib import Path

import activity as A
from activity import Diagram

OUT = Path(sys.argv[1])

# lane colours: (body, header)
PAT = ('#eef4fc', '#6c8ebf')
DOC = ('#fff5e8', '#d79b00')
LAB = ('#f5eff8', '#9673a6')
ADM = ('#fcefee', '#b85450')
SYS = ('#f6f6f6', '#6b6b6b')
SYSTEM = 'HealthNexus BD System'

MAIN, SIDE = 150, -170   # two columns inside a 640-wide actor lane


def patient():
    d = Diagram('Activity Diagram — Patient', [('Patient', *PAT, 1880), (SYSTEM, *SYS, 460)])
    m, s = 560, 200   # main flow / side column inside the wide patient lane
    d.n('start', 'start', 0, 0, dx=m)
    d.n('reg', 'action', 0, 1, 'Register (name, NID,\nphone, email, password)', dx=m)
    d.n('valid', 'decision', 1, 2, 'Details valid &\nnot used before?')
    d.n('fix', 'action', 0, 2, 'Correct the details', dx=s)
    d.n('create', 'action', 1, 3.2, 'Create account &\ngenerate UHID')
    d.n('login', 'action', 0, 4.3, 'Log in\n(email or phone)', dx=m)
    d.n('cred', 'decision', 1, 5.5, 'Password\ncorrect?')
    d.n('reset', 'action', 0, 5.5, 'Reset password\n(email / SMS code)', dx=s)
    d.n('dash', 'action', 0, 6.8, 'Open patient dashboard', dx=m)
    d.n('fork', 'bar', 0, 7.9, '1860')
    tasks = [('t1', 'Manage health\nprofile'), ('t2', 'View records,\nprescriptions & side effects'),
             ('t3', 'View & download\nlab reports'), ('t4', 'Deny a request /\nrevoke doctor access'),
             ('t5', 'Chat with AI\nHealth Assistant'), ('t6', 'View who accessed\nmy data')]
    for i, (tid, text) in enumerate(tasks):
        d.n(tid, 'action', 0, 9, text, dx=-775 + i * 310)
    d.n('join', 'bar', 0, 10.1, '1860')
    d.n('logout', 'action', 0, 11.1, 'Log out', dx=m)
    d.n('end', 'end', 0, 12.1, dx=m)

    d.e('start', 'reg')
    d.e('reg', 'valid', mode='hv')
    d.e('valid', 'fix', 'No', mode='h')
    d.e('fix', 'reg', mode='vh')
    d.e('valid', 'create', 'Yes')
    d.e('create', 'login', mode='hv')
    d.e('login', 'cred', mode='hv')
    d.e('cred', 'reset', 'No', mode='h')
    d.e('reset', 'login', mode='vh')
    d.e('cred', 'dash', 'Yes', mode='down-across')
    d.e('dash', 'fork', mode='join')
    for tid, _ in tasks:
        d.e('fork', tid, mode='drop')
        d.e(tid, 'join', mode='join')
    d.e('join', 'logout', mode='drop')
    d.e('logout', 'end')
    return d


